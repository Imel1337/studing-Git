from datetime import datetime  # Импорт класса datetime из модуля datetime для работы с датой и временем
from math import sqrt  # Импорт функции sqrt из модуля math для вычисления квадратного корня

def main(**kwargs):
    """
    Функция принимает произвольное количество именованных аргументов
    и вычисляет длину вектора для каждого переданного списка координат
    """
    for key in kwargs.items():  # Итерация по элементам словаря kwargs (key - кортеж (имя_аргумента, значение))
        result = sqrt(key[1][0] ** 2 + key[1][1] ** 2)  # Вычисление длины вектора по формуле sqrt(x² + y²)
        print(result)  # Вывод результата в консоль

if __name__ == '__main__':  # Проверка, что скрипт запущен напрямую, а не импортирован
    start_time = datetime.now()  # Запись текущего времени начала выполнения программы
    main(  # Вызов функции main с передачей именованных аргументов
        one=[10, 3],    # Вектор с координатами (10, 3)
        two=[5, 4],     # Вектор с координатами (5, 4)
        three=[15, 13], # Вектор с координатами (15, 13)
        four=[93, 53],  # Вектор с координатами (93, 53)
        five=[133, 15]  # Вектор с координатами (133, 15)
    )
    time_costs = datetime.now() - start_time  # Вычисление времени выполнения программы
    print(f"Время выполнения программы - {time_costs}")  # Вывод времени выполнения